"""Round 9: model-native text for teacher-forced quality checks of instruction-tuned models whose raw-text PPL on
the frozen corpus is too high for argmax agreement to mean anything (Gemma-4-IT: PPL ~300 on the corpus).
Text = chat-templated question + greedy continuation generated by the fp32-truth MoE arm (neither stock nor
our kernels produce it, so the check favours neither).

    [MOELAB_UNIVERSAL=1] .venv-latest/bin/python scripts/r9_native_text.py MODEL OUT.txt [N_TOKENS]
"""
import os
import sys

from mlx_lm import load, stream_generate
from mlx_lm.sample_utils import make_sampler

from moelab import e2e
from moelab.mlx_backend import load_variant

model_id, out = sys.argv[1], sys.argv[2]
n = int(sys.argv[3]) if len(sys.argv) > 3 else 400
model, tok = load(model_id)
e2e.UNIVERSAL = os.environ.get("MOELAB_UNIVERSAL") == "1"   # families without a dedicated patch
cls, _ = e2e.patch(model, load_variant("moelab/variants/fp32_truth_q4.py"))
cls._use_variant = True
q = ("Explain how a mixture-of-experts transformer layer routes tokens to experts, why it saves compute, "
     "and what problems appear when serving it on a laptop GPU.")
prompt = tok.apply_chat_template([{"role": "user", "content": q}], add_generation_prompt=True, tokenize=False)
text = prompt + "".join(r.text for r in stream_generate(model, tok, prompt, max_tokens=n, sampler=make_sampler(temp=0.0)))
open(out, "w").write(text)
print(text[-600:])
